// Snapshot is what BareSQL reads from the system catalogs, all inside one
// read-only transaction so the parts agree with each other.
type Snapshot struct {
	Server  ServerInfo
	Auditor Auditor

	Roles       map[uint32]*Role
	RoleByName  map[string]*Role
	Memberships []Membership
	Schemas     map[uint32]*Schema
	Relations   map[uint32]*Relation
	Policies    []Policy
	Functions   []*Function
	DefaultACLs []DefaultACL
	Mappings    []UserMapping
	// Inherits maps a child table to its parents (classic inheritance and
	// partitions).
	Inherits map[uint32][]uint32

	// NotSeen lists what the auditor's login couldn't read.
	NotSeen []NotSeen
}

type ServerInfo struct {
	VersionNum int    // server_version_num, e.g. 160015
	Version    string // server_version
	Database   string
	DBOwner    uint32
	Encoding   string
}

type Auditor struct {
	Role      string
	Superuser bool
}

type Role struct {
	OID                                  uint32
	Name                                 string
	Super, Inherit, CreateRole, CreateDB bool
	CanLogin, Replication, BypassRLS     bool
	ConnLimit                            int
	ValidUntil                           string
	PasswordKind                         string // none, md5, scram-sha-256, other; "" when unknown
	Predefined                           bool   // pg_* role shipped with PostgreSQL
}

// Membership: Member is a member of Role.
type Membership struct {
	Role, Member, Grantor uint32
	Admin                 bool
	Inherit               bool // privileges flow to the member without SET ROLE
	Set                   bool // the member may SET ROLE to Role
	Implicit              bool // pg_database_owner's membership of the database owner
}

// ACLItem is one privilege from an access list; Grantee 0 is PUBLIC.
type ACLItem struct {
	Grantee, Grantor uint32
	Priv             string // SELECT, INSERT, UPDATE, DELETE, TRUNCATE, USAGE, EXECUTE ...
	Grantable        bool
}

type Schema struct {
	OID     uint32
	Name    string
	Owner   uint32
	ACL     []ACLItem
	Audited bool // relations in it are part of the audit
}

type Relation struct {
	OID             uint32
	Schema          uint32
	Name            string
	Kind            byte // r table, p partitioned table, v view, m materialized view, f foreign table
	Owner           uint32
	ACL             []ACLItem
	RLS, ForceRLS   bool
	SecurityInvoker bool // views: run with the reader's rights (15 and later)
	IsPartition     bool
	PartitionRoot   uint32
	Columns         []*Column
	// Lineage of each view or materialized view column, by attnum.
	Lineage    map[int]colLineage
	LineageErr string
	// Needs: every privilege a view's query is checked for when read.
	Needs []viewNeed
	// Foreign tables: the server they read from, and its wrapper.
	ForeignServer uint32
	ServerName    string
	FDW           string
}

type Column struct {
	Attnum    int
	Name      string
	TypeOID   uint32
	Type      string // format_type output
	Generated byte   // 's' stored, 'v' virtual (18), 0 none
	ACL       []ACLItem
	// Readable: the value can be read as text without running anything
	// but C output functions (see sampleable types).
	Readable bool
	JSON     bool
	Binary   bool
}

type Policy struct {
	Rel        uint32
	Name       string
	Permissive bool
	Cmd        string // ALL, SELECT, INSERT, UPDATE, DELETE
	Roles      []uint32
	Using      string
	Check      string
}

type Function struct {
	OID       uint32
	Schema    uint32
	Name      string
	Args      string
	Owner     uint32
	SecDef    bool
	Lang      string
	Config    []string
	ACL       []ACLItem
	Builtin   bool // a server-access function from pg_catalog
	Signature string
}

type DefaultACL struct {
	Creator uint32 // objects this role creates ...
	Schema  uint32 // ... in this schema (0: anywhere)
	ObjType string // tables, sequences, functions, types, schemas
	ACL     []ACLItem
}

// UserMapping lets Role (0: PUBLIC) reach a foreign server. Its options,
// which can hold passwords, are never read.
type UserMapping struct {
	Server    string
	ServerOID uint32
	FDW       string
	Role      uint32
}

type NotSeen struct {
	What string `json:"what"`
	Why  string `json:"why"`
}

// Options select what is audited.
type Options struct {
	Schemas []string // empty: every schema except the system ones
	Logins  []string // empty: every role that can log in
}

type loader struct {
	ctx  context.Context
	c    *pgwire.Conn
	snap *Snapshot
}

func (l *loader) query(sql string, args ...any) ([][]pgwire.Value, error) {
	r, err := l.c.QueryArgs(l.ctx, sql, args...)
	if err != nil {
		return nil, fmt.Errorf("%w\nquery: %s", err, firstLine(sql))
	}
	return r.Rows, nil
}

func firstLine(s string) string {
	s = strings.TrimSpace(s)
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		return s[:i] + " ..."
	}
	return s
}

func u32(v pgwire.Value) uint32 {
	n, _ := strconv.ParseUint(v.String(), 10, 32)
	return uint32(n)
}

func num(v pgwire.Value) int {
	n, _ := strconv.Atoi(v.String())
	return n
}

func boolv(v pgwire.Value) bool { return v.String() == "t" }

// parseTextArray reads a one-dimensional text[] or oid[] in text form:
// {a,"b c",NULL}.
func parseTextArray(s string) []string {
	s = strings.TrimSpace(s)
	if len(s) < 2 || s[0] != '{' || s[len(s)-1] != '}' {
		return nil
	}
	s = s[1 : len(s)-1]
	var out []string
	var cur strings.Builder
	inQ, quoted := false, false
	for i := 0; i < len(s); i++ {
		ch := s[i]
		switch {
		case inQ && ch == '\\' && i+1 < len(s):
			cur.WriteByte(s[i+1])
			i++
		case ch == '"':
			inQ = !inQ
			quoted = true
		case ch == ',' && !inQ:
			out = append(out, arrayItem(cur.String(), quoted))
			cur.Reset()
			quoted = false
		default:
			cur.WriteByte(ch)
		}
	}
	if cur.Len() > 0 || quoted || len(out) > 0 {
		out = append(out, arrayItem(cur.String(), quoted))
	}
	return out
}

func arrayItem(s string, quoted bool) string {
	if !quoted && s == "NULL" {
		return ""
	}
	return s
}

// systemSchema reports schemas that hold no user data.
func systemSchema(name string) bool {
	return name == "pg_catalog" || name == "information_schema" || strings.HasPrefix(name, "pg_toast") ||
		strings.HasPrefix(name, "pg_temp_")
}

// Load reads the catalogs. c must be inside the read-only transaction
// that Run opens.
func Load(ctx context.Context, c *pgwire.Conn, opt Options) (*Snapshot, error) {
	l := &loader{ctx: ctx, c: c, snap: &Snapshot{
		Roles: map[uint32]*Role{}, RoleByName: map[string]*Role{}, Schemas: map[uint32]*Schema{},
		Relations: map[uint32]*Relation{}, Inherits: map[uint32][]uint32{},
	}}
	steps := []func() error{l.server, l.roles, l.memberships, func() error { return l.schemas(opt.Schemas) },
		l.relations, l.columns, l.views, l.policies, l.functions, l.defaultACLs, l.mappings, l.inherits, l.foreignTables}
	for _, step := range steps {
		if err := step(); err != nil {
			return nil, err
		}
	}
	return l.snap, nil
}

func (l *loader) server() error {
	rows, err := l.query(`SELECT pg_catalog.current_setting('server_version_num')::int,
		pg_catalog.current_setting('server_version'), pg_catalog.current_database(), d.datdba,
		pg_catalog.pg_encoding_to_char(d.encoding), current_user, r.rolsuper
		FROM pg_catalog.pg_database d, pg_catalog.pg_roles r
		WHERE d.datname = pg_catalog.current_database() AND r.rolname = current_user`)
	if err != nil {
		return err
	}
	if len(rows) != 1 {
		return fmt.Errorf("audit: can't read the current database and role")
	}
	r := rows[0]
	l.snap.Server = ServerInfo{VersionNum: num(r[0]), Version: r[1].String(), Database: r[2].String(),
		DBOwner: u32(r[3]), Encoding: r[4].String()}
	l.snap.Auditor = Auditor{Role: r[5].String(), Superuser: boolv(r[6])}
	if l.snap.Server.VersionNum < 130000 {
		return fmt.Errorf("audit: PostgreSQL %s is not supported (13 or later)", l.snap.Server.Version)
	}
	return nil
}

func (l *loader) roles() error {
	rows, err := l.query(`SELECT oid, rolname, rolsuper, rolinherit, rolcreaterole, rolcreatedb, rolcanlogin,
		rolreplication, rolbypassrls, rolconnlimit, COALESCE(rolvaliduntil::text, '')
		FROM pg_catalog.pg_roles`)
	if err != nil {
		return err
	}
	for _, r := range rows {
		role := &Role{OID: u32(r[0]), Name: r[1].String(), Super: boolv(r[2]), Inherit: boolv(r[3]),
			CreateRole: boolv(r[4]), CreateDB: boolv(r[5]), CanLogin: boolv(r[6]), Replication: boolv(r[7]),
			BypassRLS: boolv(r[8]), ConnLimit: num(r[9]), ValidUntil: r[10].String()}
		// Predefined roles have OIDs below FirstNormalObjectId (16384), as
		// does the bootstrap superuser (10).
		role.Predefined = role.OID < 16384 && strings.HasPrefix(role.Name, "pg_")
		l.snap.Roles[role.OID] = role
		l.snap.RoleByName[role.Name] = role
	}
	if !l.snap.Auditor.Superuser {
		l.snap.NotSeen = append(l.snap.NotSeen, NotSeen{What: "password types (md5 or SCRAM)",
			Why: "only a superuser can read pg_authid"})
		return nil
	}
	rows, err = l.query(`SELECT oid, CASE WHEN rolpassword IS NULL THEN 'none'
		WHEN rolpassword LIKE 'md5%' THEN 'md5' WHEN rolpassword LIKE 'SCRAM-SHA-256$%' THEN 'scram-sha-256'
		ELSE 'other' END FROM pg_catalog.pg_authid`)
	if err != nil {
		return err
	}
	for _, r := range rows {
		if role := l.snap.Roles[u32(r[0])]; role != nil {
			role.PasswordKind = r[1].String()
		}
	}
	return nil
}

func (l *loader) memberships() error {
	sql := `SELECT roleid, member, grantor, admin_option, true, true FROM pg_catalog.pg_auth_members`
	pg16 := l.snap.Server.VersionNum >= 160000
	if pg16 {
		sql = `SELECT roleid, member, grantor, admin_option, inherit_option, set_option FROM pg_catalog.pg_auth_members`
	}
	rows, err := l.query(sql)
	if err != nil {
		return err
	}
	for _, r := range rows {
		m := Membership{Role: u32(r[0]), Member: u32(r[1]), Grantor: u32(r[2]), Admin: boolv(r[3]),
			Inherit: boolv(r[4]), Set: boolv(r[5])}
		if !pg16 {
			// Before 16 the member's own INHERIT attribute decides, and any
			// member may SET ROLE.
			if member := l.snap.Roles[m.Member]; member != nil {
				m.Inherit = member.Inherit
			}
		}
		l.snap.Memberships = append(l.snap.Memberships, m)
	}
	// The database owner is implicitly a member of pg_database_owner (14+).
	if dbo := l.snap.RoleByName["pg_database_owner"]; dbo != nil {
		inherit := pg16
		if owner := l.snap.Roles[l.snap.Server.DBOwner]; owner != nil && !pg16 {
			inherit = owner.Inherit
		}
		l.snap.Memberships = append(l.snap.Memberships, Membership{Role: dbo.OID, Member: l.snap.Server.DBOwner,
			Inherit: inherit, Implicit: true})
	}
	return nil
}

func (l *loader) acl(sql string, args ...any) (map[uint32][]ACLItem, error) {
	rows, err := l.query(sql, args...)
	if err != nil {
		return nil, err
	}
	out := map[uint32][]ACLItem{}
	for _, r := range rows {
		id := u32(r[0])
		if r[1].Null { // no ACL at all (nothing granted)
			if _, ok := out[id]; !ok {
				out[id] = nil
			}
			continue
		}
		out[id] = append(out[id], ACLItem{Grantor: u32(r[1]), Grantee: u32(r[2]), Priv: r[3].String(), Grantable: boolv(r[4])})
	}
	return out, nil
}

func (l *loader) schemas(only []string) error {
	rows, err := l.query(`SELECT oid, nspname, nspowner FROM pg_catalog.pg_namespace`)
	if err != nil {
		return err
	}
	want := map[string]bool{}
	for _, s := range only {
		want[s] = true
	}
	for _, r := range rows {
		s := &Schema{OID: u32(r[0]), Name: r[1].String(), Owner: u32(r[2])}
		if len(want) > 0 {
			s.Audited = want[s.Name]
			delete(want, s.Name)
		} else {
			s.Audited = !systemSchema(s.Name)
		}
		l.snap.Schemas[s.OID] = s
	}
	for name := range want {
		return fmt.Errorf("audit: schema %q does not exist", name)
	}
	acls, err := l.acl(`SELECT n.oid, a.grantor, a.grantee, a.privilege_type, a.is_grantable
		FROM pg_catalog.pg_namespace n
		LEFT JOIN LATERAL pg_catalog.aclexplode(COALESCE(n.nspacl, pg_catalog.acldefault('n', n.nspowner))) a ON true`)
	if err != nil {
		return err
	}
	for id, acl := range acls {
		if s := l.snap.Schemas[id]; s != nil {
			s.ACL = acl
		}
	}
	return nil
}

func (l *loader) auditedSchemaOIDs() string {
	var ids []string
	for _, s := range l.snap.Schemas {
		if s.Audited {
			ids = append(ids, strconv.FormatUint(uint64(s.OID), 10))
		}
	}
	sort.Strings(ids)
	return "{" + strings.Join(ids, ",") + "}"
}

func (l *loader) relations() error {
	schemas := l.auditedSchemaOIDs()
	rows, err := l.query(`SELECT c.oid, c.relnamespace, c.relname, c.relkind, c.relowner, c.relrowsecurity,
		c.relforcerowsecurity, c.relispartition, COALESCE(pg_catalog.pg_partition_root(c.oid)::pg_catalog.oid, 0),
		COALESCE(c.reloptions::text, '{}')
		FROM pg_catalog.pg_class c
		WHERE c.relkind IN ('r','p','v','m','f') AND c.relnamespace = ANY($1::oid[])`, schemas)
	if err != nil {
		return err
	}
	for _, r := range rows {
		rel := &Relation{OID: u32(r[0]), Schema: u32(r[1]), Name: r[2].String(), Kind: firstChar(r[3].String()),
			Owner: u32(r[4]), RLS: boolv(r[5]), ForceRLS: boolv(r[6]), IsPartition: boolv(r[7]),
			PartitionRoot: u32(r[8])}
		if rel.PartitionRoot == rel.OID {
			rel.PartitionRoot = 0
		}
		for _, o := range parseTextArray(r[9].String()) {
			k, v, _ := strings.Cut(o, "=")
			if strings.EqualFold(k, "security_invoker") {
				rel.SecurityInvoker = truthy(v)
			}
		}
		l.snap.Relations[rel.OID] = rel
	}
	acls, err := l.acl(`SELECT c.oid, a.grantor, a.grantee, a.privilege_type, a.is_grantable
		FROM pg_catalog.pg_class c
		LEFT JOIN LATERAL pg_catalog.aclexplode(COALESCE(c.relacl, pg_catalog.acldefault('r', c.relowner))) a ON true
		WHERE c.relkind IN ('r','p','v','m','f') AND c.relnamespace = ANY($1::oid[])`, schemas)
	if err != nil {
		return err
	}
	for id, acl := range acls {
		if rel := l.snap.Relations[id]; rel != nil {
			rel.ACL = acl
		}
	}
	return nil
}

// truthy reads a boolean reloption the way PostgreSQL's parse_bool does.
func truthy(v string) bool {
	switch strings.ToLower(v) {
	case "true", "on", "yes", "1", "t", "y":
		return true
	}
	return false
}

func firstChar(s string) byte {
	if s == "" {
		return 0
	}
	return s[0]
}

// readableTypes are the types whose values can be read as text running only
// C code: base types and enums whose output function is internal or C,
// domains over them and arrays of them.
const readableTypesSQL = `WITH RECURSIVE ok(oid) AS (
	SELECT t.oid FROM pg_catalog.pg_type t
	JOIN pg_catalog.pg_proc p ON p.oid = t.typoutput
	JOIN pg_catalog.pg_language g ON g.oid = p.prolang
	WHERE t.typtype IN ('b','e') AND t.typcategory <> 'A' AND g.lanname IN ('internal','c')
	UNION
	SELECT t.oid FROM pg_catalog.pg_type t JOIN ok
	ON (t.typtype = 'd' AND t.typbasetype = ok.oid) OR (t.typcategory = 'A' AND t.typelem = ok.oid)
)`

func (l *loader) columns() error {
	schemas := l.auditedSchemaOIDs()
	rows, err := l.query(readableTypesSQL+`
		SELECT a.attrelid, a.attnum, a.attname, a.atttypid, pg_catalog.format_type(a.atttypid, a.atttypmod),
		COALESCE(a.attgenerated, ''), (a.atttypid IN (SELECT oid FROM ok)),
		(pg_catalog.format_type(COALESCE(NULLIF(t.typbasetype, 0), a.atttypid), NULL) IN ('json', 'jsonb')),
		(COALESCE(NULLIF(t.typbasetype, 0), a.atttypid) = 'pg_catalog.bytea'::pg_catalog.regtype)
		FROM pg_catalog.pg_attribute a
		JOIN pg_catalog.pg_class c ON c.oid = a.attrelid
		JOIN pg_catalog.pg_type t ON t.oid = a.atttypid
		WHERE a.attnum > 0 AND NOT a.attisdropped
		AND c.relkind IN ('r','p','v','m','f') AND c.relnamespace = ANY($1::oid[])
		ORDER BY a.attrelid, a.attnum`, schemas)
	if err != nil {
		return err
	}
	for _, r := range rows {
		rel := l.snap.Relations[u32(r[0])]
		if rel == nil {
			continue
		}
		col := &Column{Attnum: num(r[1]), Name: r[2].String(), TypeOID: u32(r[3]), Type: r[4].String(),
			Generated: firstChar(r[5].String()), Readable: boolv(r[6]), JSON: boolv(r[7]), Binary: boolv(r[8])}
		rel.Columns = append(rel.Columns, col)
	}
	rows, err = l.query(`SELECT a.attrelid, a.attnum, x.grantor, x.grantee, x.privilege_type, x.is_grantable
		FROM pg_catalog.pg_attribute a
		JOIN pg_catalog.pg_class c ON c.oid = a.attrelid
		CROSS JOIN LATERAL pg_catalog.aclexplode(a.attacl) x
		WHERE a.attacl IS NOT NULL AND a.attnum > 0 AND NOT a.attisdropped
		AND c.relkind IN ('r','p','v','m','f') AND c.relnamespace = ANY($1::oid[])`, schemas)
	if err != nil {
		return err
	}
	for _, r := range rows {
		rel := l.snap.Relations[u32(r[0])]
		if rel == nil {
			continue
		}
		if col := rel.Column(num(r[1])); col != nil {
			col.ACL = append(col.ACL, ACLItem{Grantor: u32(r[2]), Grantee: u32(r[3]), Priv: r[4].String(), Grantable: boolv(r[5])})
		}
	}
	return nil
}

// Column returns the column with the given attnum, or nil.
func (r *Relation) Column(attnum int) *Column {
	for _, c := range r.Columns {
		if c.Attnum == attnum {
			return c
		}
	}
	return nil
}

func (l *loader) views() error {
	rows, err := l.query(`SELECT r.ev_class, r.ev_action FROM pg_catalog.pg_rewrite r
		JOIN pg_catalog.pg_class c ON c.oid = r.ev_class
		WHERE r.rulename = '_RETURN' AND c.relkind IN ('v','m') AND c.relnamespace = ANY($1::oid[])`,
		l.auditedSchemaOIDs())
	if err != nil {
		return err
	}
	for _, r := range rows {
		rel := l.snap.Relations[u32(r[0])]
		if rel == nil {
			continue
		}
		lin, err := viewLineage(r[1].String())
		if err != nil {
			rel.LineageErr = err.Error()
			continue
		}
		if rel.Needs, err = viewNeeds(r[1].String()); err != nil {
			rel.LineageErr = err.Error()
			continue
		}
		rel.Lineage = map[int]colLineage{}
		for _, cl := range lin {
			rel.Lineage[cl.Resno] = cl
		}
	}
	return nil
}

func (l *loader) policies() error {
	rows, err := l.query(`SELECT p.polrelid, p.polname, p.polpermissive, p.polcmd, p.polroles::text,
		COALESCE(pg_catalog.pg_get_expr(p.polqual, p.polrelid), ''),
		COALESCE(pg_catalog.pg_get_expr(p.polwithcheck, p.polrelid), '')
		FROM pg_catalog.pg_policy p JOIN pg_catalog.pg_class c ON c.oid = p.polrelid
		WHERE c.relnamespace = ANY($1::oid[]) ORDER BY p.polrelid, p.polname`, l.auditedSchemaOIDs())
	if err != nil {
		return err
	}
	cmds := map[string]string{"*": "ALL", "r": "SELECT", "a": "INSERT", "w": "UPDATE", "d": "DELETE"}
	for _, r := range rows {
		p := Policy{Rel: u32(r[0]), Name: r[1].String(), Permissive: boolv(r[2]), Cmd: cmds[r[3].String()],
			Using: r[5].String(), Check: r[6].String()}
		for _, s := range parseTextArray(r[4].String()) {
			n, _ := strconv.ParseUint(s, 10, 32)
			p.Roles = append(p.Roles, uint32(n))
		}
		l.snap.Policies = append(l.snap.Policies, p)
	}
	return nil
}

// serverAccessFunctions run with the server's own file or program rights.
// Superusers have them all; others only by explicit grant.
var serverAccessFunctions = []string{
	"pg_catalog.pg_read_file(text)",
	"pg_catalog.pg_read_file(text,bigint,bigint)",
	"pg_catalog.pg_read_file(text,bigint,bigint,boolean)",
	"pg_catalog.pg_read_binary_file(text)",
	"pg_catalog.pg_read_binary_file(text,bigint,bigint,boolean)",
	"pg_catalog.pg_ls_dir(text)",
	"pg_catalog.pg_ls_dir(text,boolean,boolean)",
	"pg_catalog.pg_stat_file(text)",
	"pg_catalog.lo_import(text)",
	"pg_catalog.lo_import(text,oid)",
	"pg_catalog.lo_export(oid,text)",
}

func (l *loader) functions() error {
	rows, err := l.query(`SELECT p.oid, p.pronamespace, p.proname, pg_catalog.pg_get_function_identity_arguments(p.oid),
		p.proowner, p.prosecdef, g.lanname, COALESCE(p.proconfig::text, '{}'), p.oid::pg_catalog.regprocedure::text, false
		FROM pg_catalog.pg_proc p JOIN pg_catalog.pg_language g ON g.oid = p.prolang
		WHERE p.prosecdef AND p.pronamespace <> 'pg_catalog'::pg_catalog.regnamespace
		AND p.pronamespace <> 'information_schema'::pg_catalog.regnamespace
		UNION ALL
		SELECT p.oid, p.pronamespace, p.proname, pg_catalog.pg_get_function_identity_arguments(p.oid),
		p.proowner, p.prosecdef, g.lanname, '{}', p.oid::pg_catalog.regprocedure::text, true
		FROM pg_catalog.pg_proc p JOIN pg_catalog.pg_language g ON g.oid = p.prolang
		WHERE p.oid = ANY(ARRAY(SELECT pg_catalog.to_regprocedure(s) FROM pg_catalog.unnest($1::text[]) s))`,
		"{"+strings.Join(quoteAll(serverAccessFunctions), ",")+"}")
	if err != nil {
		return err
	}
	byOID := map[uint32]*Function{}
	for _, r := range rows {
		f := &Function{OID: u32(r[0]), Schema: u32(r[1]), Name: r[2].String(), Args: r[3].String(), Owner: u32(r[4]),
			SecDef: boolv(r[5]), Lang: r[6].String(), Config: parseTextArray(r[7].String()), Signature: r[8].String(),
			Builtin: boolv(r[9])}
		l.snap.Functions = append(l.snap.Functions, f)
		byOID[f.OID] = f
	}
	var ids []string
	for id := range byOID {
		ids = append(ids, strconv.FormatUint(uint64(id), 10))
	}
	acls, err := l.acl(`SELECT p.oid, a.grantor, a.grantee, a.privilege_type, a.is_grantable
		FROM pg_catalog.pg_proc p
		LEFT JOIN LATERAL pg_catalog.aclexplode(COALESCE(p.proacl, pg_catalog.acldefault('f', p.proowner))) a ON true
		WHERE p.oid = ANY($1::oid[])`, "{"+strings.Join(ids, ",")+"}")
	if err != nil {
		return err
	}
	for id, acl := range acls {
		if f := byOID[id]; f != nil {
			f.ACL = acl
		}
	}
	sort.Slice(l.snap.Functions, func(i, j int) bool { return l.snap.Functions[i].Signature < l.snap.Functions[j].Signature })
	return nil
}

func quoteAll(ss []string) []string {
	out := make([]string, len(ss))
	for i, s := range ss {
		out[i] = `"` + s + `"`
	}
	return out
}

func (l *loader) defaultACLs() error {
	rows, err := l.query(`SELECT d.defaclrole, d.defaclnamespace, d.defaclobjtype, a.grantor, a.grantee,
		a.privilege_type, a.is_grantable
		FROM pg_catalog.pg_default_acl d CROSS JOIN LATERAL pg_catalog.aclexplode(d.defaclacl) a
		ORDER BY d.defaclrole, d.defaclnamespace, d.defaclobjtype`)
	if err != nil {
		return err
	}
	types := map[string]string{"r": "tables", "S": "sequences", "f": "functions", "T": "types", "n": "schemas", "L": "large objects"}
	index := map[string]int{}
	for _, r := range rows {
		key := r[0].String() + "/" + r[1].String() + "/" + r[2].String()
		i, ok := index[key]
		if !ok {
			l.snap.DefaultACLs = append(l.snap.DefaultACLs, DefaultACL{Creator: u32(r[0]), Schema: u32(r[1]), ObjType: types[r[2].String()]})
			i = len(l.snap.DefaultACLs) - 1
			index[key] = i
		}
		d := &l.snap.DefaultACLs[i]
		d.ACL = append(d.ACL, ACLItem{Grantor: u32(r[3]), Grantee: u32(r[4]), Priv: r[5].String(), Grantable: boolv(r[6])})
	}
	return nil
}

func (l *loader) mappings() error {
	rows, err := l.query(`SELECT s.srvname, s.oid, w.fdwname, m.umuser
		FROM pg_catalog.pg_user_mappings m
		JOIN pg_catalog.pg_foreign_server s ON s.oid = m.srvid
		JOIN pg_catalog.pg_foreign_data_wrapper w ON w.oid = s.srvfdw
		ORDER BY s.srvname`)
	if err != nil {
		return err
	}
	for _, r := range rows {
		l.snap.Mappings = append(l.snap.Mappings, UserMapping{Server: r[0].String(), ServerOID: u32(r[1]), FDW: r[2].String(), Role: u32(r[3])})
	}
	return nil
}

func (l *loader) foreignTables() error {
	rows, err := l.query(`SELECT ft.ftrelid, s.oid, s.srvname, w.fdwname
		FROM pg_catalog.pg_foreign_table ft
		JOIN pg_catalog.pg_foreign_server s ON s.oid = ft.ftserver
		JOIN pg_catalog.pg_foreign_data_wrapper w ON w.oid = s.srvfdw`)
	if err != nil {
		return err
	}
	for _, r := range rows {
		if rel := l.snap.Relations[u32(r[0])]; rel != nil {
			rel.ForeignServer, rel.ServerName, rel.FDW = u32(r[1]), r[2].String(), r[3].String()
		}
	}
	return nil
}

func (l *loader) inherits() error {
	rows, err := l.query(`SELECT inhrelid, inhparent FROM pg_catalog.pg_inherits ORDER BY inhrelid, inhseqno`)
	if err != nil {
		return err
	}
	for _, r := range rows {
		child := u32(r[0])
		l.snap.Inherits[child] = append(l.snap.Inherits[child], u32(r[1]))
	}
	return nil
}

// QualifiedName is schema.name, quoted where needed.
func (s *Snapshot) QualifiedName(rel *Relation) string {
	schema := "?"
	if sc := s.Schemas[rel.Schema]; sc != nil {
		schema = sc.Name
	}
	return quoteIdent(schema) + "." + quoteIdent(rel.Name)
}

// RoleName returns a role's name as reports show it, PUBLIC for 0. A name
// that isn't plain lower case is quoted, as in SQL, so a real role named
// "PUBLIC" never reads as the PUBLIC pseudo-role.
func (s *Snapshot) RoleName(oid uint32) string {
	if oid == 0 {
		return "PUBLIC"
	}
	if r := s.Roles[oid]; r != nil {
		return quoteIdent(r.Name)
	}
	return fmt.Sprintf("(role %d)", oid)
}

// quoteIdent quotes an identifier unless it is a plain lower-case name.
// Control and other unprintable characters are written as escapes (\n,
// \x1b), so a name can't start a line of its own in text output or send
// codes to a terminal; a name holding one also has its backslashes doubled,
// so the escapes can't be faked.
func quoteIdent(s string) string {
	plain := s != ""
	for i, ch := range s {
		if !(ch == '_' || ch >= 'a' && ch <= 'z' || i > 0 && (ch >= '0' && ch <= '9' || ch == '$')) {
			plain = false
			break
		}
	}
	if plain && !reservedWord[s] {
		return s
	}
	q := strings.ReplaceAll(s, `"`, `""`)
	if strings.IndexFunc(s, unprintable) >= 0 {
		q = escapeText(strings.ReplaceAll(q, `\`, `\\`))
	}
	return `"` + q + `"`
}

func unprintable(r rune) bool { return !unicode.IsPrint(r) }

// escapeText writes the unprintable characters of s as Go escapes.
func escapeText(s string) string {
	if strings.IndexFunc(s, unprintable) < 0 {
		return s
	}
	var b strings.Builder
	for _, r := range s {
		switch {
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\r':
			b.WriteString(`\r`)
		case r == '\t':
			b.WriteString(`\t`)
		case unprintable(r) && r < 0x100:
			fmt.Fprintf(&b, `\x%02x`, r)
		case unprintable(r):
			fmt.Fprintf(&b, `\u%04x`, r)
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

// cleanText is escapeText for free text printed to a terminal or a text
// file: messages that may carry names, such as the server's own errors.
func cleanText(s string) string { return escapeText(s) }

// CleanText escapes the unprintable characters of a message for a
// terminal: the CLI prints the server's errors through it.
func CleanText(s string) string { return escapeText(s) }

